export async function seedDatabase() {
  try {
    const mongoUri = process.env.MONGO_URI || 'mongodb://localhost:27017/shopnexus';
    await mongoose.connect(mongoUri);
    console.log('Connected to MongoDB for Seeding...');

    // 1. Ensure Demo Admin exists
    const adminEmail = 'admin@shopnexus.io';
    let adminUser = await User.findOne({ email: adminEmail });
    if (!adminUser) {
      const salt = await bcrypt.genSalt(10);
      const passwordHash = await bcrypt.hash('Admin@ShopNexus2026!', salt);
      adminUser = await User.create({
        name: 'Nexus Lead Admin',
        email: adminEmail,
        passwordHash,
        role: 'admin',
        isEmailVerified: true,
      });
      console.log('Seeded Root Admin: admin@shopnexus.io / Admin@ShopNexus2026!');
    }

    // 2. Ensure Verified Vendor exists
    const vendorEmail = 'vendor@apexacoustics.io';
    let vendorUser = await User.findOne({ email: vendorEmail });
    if (!vendorUser) {
      const salt = await bcrypt.genSalt(10);
      const passwordHash = await bcrypt.hash('Vendor@ShopNexus2026!', salt);
      vendorUser = await User.create({
        name: 'Apex Acoustic Studio',
        email: vendorEmail,
        passwordHash,
        role: 'vendor',
        storeName: 'Apex Acoustic Studio',
        storeDescription: 'Premier high-fidelity acoustic audio and spatial studio hardware.',
        storeBanner: 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=1600&q=80',
        storeLogo: 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=200&q=80',
        supportEmail: 'support@apexacoustics.io',
        supportPhone: '+1 (800) 427-3922',
        isEmailVerified: true,
      });
      console.log('Seeded Verified Vendor: vendor@apexacoustics.io / Vendor@ShopNexus2026!');
    }

    // 3. Clear existing products and reseed with attached vendorId
    await Product.deleteMany({});
    const productsWithVendor = PRODUCTS_DATA.map((item) => ({
      ...item,
      vendorId: vendorUser!._id,
    }));

    const createdProducts = await Product.insertMany(productsWithVendor);
    console.log(`Successfully seeded ${createdProducts.length} diverse products into MongoDB Atlas!`);

    await mongoose.disconnect();
    console.log('Database Seeding Complete!');
  } catch (error) {
    console.error('Seeding error:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  seedDatabase();
}
